#!/usr/bin/env bash
# Creates a vault secret {"username": ..., "password": <random>} if it does not exist yet (idempotent, nothing printed).
# Usage: ./scripts/vault-new-password.sh <vault-secret-name> [username]
#   ./scripts/vault-new-password.sh monitoring-grafana-admin-oracle admin
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
NAME="${1:?vault secret name}"; USER_NAME="${2:-admin}"
tf() { terraform -chdir="$ROOT/terraform/oracle" output -raw "$1"; }
VAULT="$(tf vault_ocid)"; KEY="$(tf master_key_ocid)"; COMPARTMENT="$(tf secrets_compartment_ocid)"
if [ -n "$(oci vault secret list --compartment-id "$COMPARTMENT" --vault-id "$VAULT" --name "$NAME" --lifecycle-state ACTIVE --query 'data[0].id' --raw-output 2>/dev/null)" ]; then
  echo "vault: $NAME already exists"; exit 0
fi
TMP="$(mktemp -d)"; chmod 700 "$TMP"; trap 'rm -rf "$TMP"' EXIT
python3 - "$COMPARTMENT" "$VAULT" "$KEY" "$NAME" "$USER_NAME" "$TMP/new.json" <<'PY'
import base64, json, secrets, string, sys
comp, vault, key, name, user, out = sys.argv[1:]
pw = "".join(secrets.choice(string.ascii_letters + string.digits) for _ in range(28))
content = base64.b64encode(json.dumps({"username": user, "password": pw}).encode()).decode()
json.dump({"compartmentId": comp, "vaultId": vault, "keyId": key, "secretName": name, "secretContentContent": content,
           "description": "generated by scripts/vault-new-password.sh"}, open(out, "w"))
PY
chmod 600 "$TMP/new.json"
oci vault secret create-base64 --from-json "file://$TMP/new.json" >/dev/null
echo "vault: created $NAME"
